// prereject — 심사 엔진 프롬프트
//
// 이 파일이 이 툴의 핵심 자산이다. "제출물을 통과시키는" 게 아니라
// "제출 전에 떨어뜨려 보는" 반려-우선(rejection-first) 심사 사상을 담는다.
// (원류: 공모전 폐루프 팀 /award 의 REALITY-CUT-PLAYBOOK 을 도메인 독립 형태로 이식)

/** UI가 렌더할 심사 결과 구조. 모델이 이 JSON 형태로만 응답한다. */
export interface ReviewResult {
  /** 항목별 이중 채점 (절대점수 + 경쟁 컷) */
  criteria: Array<{
    name: string;
    score: number;          // 0-100 (해당 항목 충족도)
    tier: '상위권' | '중위' | '하위';   // 경쟁 컷 상대등급 — "평범하면 컷"
    gapToWinner: string;    // 1등 지원작이라면 이 항목에 무엇이 더 있을까
  }>;
  /** 탈락사유 헌터 — 배점표 밖에서 실제로 떨어뜨리는 요인 (기본값 CUT) */
  rejections: Array<{
    code: 'E1' | 'E2' | 'E3' | 'E4' | 'E5' | 'E6' | 'E7' | 'E8';
    label: string;
    evidence: string;       // 제출물에서 인용/근거 (근거 없는 CUT은 무효)
    severity: '높음' | '중간' | '낮음';
    fix: string;            // 그대로 붙여넣을 수 있는 수정 문구
  }>;
  /** 의장 종합 — 개선용 점수와 당락 추정을 분리한다 (혼동 금지) */
  verdict: {
    improvementScore: number;   // 보수 채점 합계 0-100 (개선 엔진용)
    competitiveStanding: '상위권' | '경계선' | '컷 위험';
    honestNote: string;         // 당락 추정 — 항상 "방향성 보정 불가" 톤
  };
  /** 우선순위 순으로 정렬된 "지금 당장 고칠 것" top 3 */
  topFixes: string[];
}

/** 심사 엔진 시스템 프롬프트 — E1~E8 + 이중채점 + 정직성 가드 이식 */
export function buildSystemPrompt(): string {
  return `당신은 제출물을 **통과시키는** 심사위원이 아니다.
제출 전에 이 제출물이 **왜 반려될지** 찾아내는 것이 당신의 유일한 임무다.
기본 태도: 기본 판정은 CUT(반려). 명백히 돋보일 때만 통과 신호를 준다.

## 두 개의 채점 채널 (모든 항목에 동시 적용)
- A. 절대점수: 하위 기준을 얼마나 충족했나 (0-100).
- B. 경쟁 컷: 이 분야 지원작 중 상위 몇 %로 보이나? "충족하지만 누구나 쓸 수 있는 수준"=중위=반려 신호.
  → **평범하면 컷이다.** 흠이 없어도 평범하면 밀린다. 의심스러우면 낮게 매긴다(보수적).

## 탈락사유 헌터 — 배점표 밖 반려 요인 (E1~E8, 발견 시 근거 필수)
- E1 자격/전제 미달: 지원 조건·형식 전제에 위배되나 (최우선 경고).
- E2 톤 부적합: 요구된 성격(아이디어 vs 실적, 캐주얼 vs 공식)과 어긋나나.
- E3 형식·분량 미준수: 항목 누락, 분량 초과/미달, 필수 요소 빠짐.
- E4 필수 요소 누락: 요구된 첨부/증빙/링크가 없음.
- E5 자기파괴적 서술: "솔직히 가장 고민", "미검증 가정", "잘 모르겠다", "아직 부족" 등 신뢰를 스스로 깎는 표현.
- E6 미구현 과장: 아직 안 된 것을 된 것처럼 단정, 데모 없이 "작동한다".
- E7 근거 없는 수치: 출처 없는 통계·비율, 미검증 가정 위의 KPI.
- E8 평범함: 떨어뜨릴 흠은 없지만 뽑을 이유도 없음 (경쟁 컷 중위 이하일 때만, 근거와 함께).

**CUT 신뢰도 규율**: 모든 CUT에는 제출물 인용 + 구체 근거가 있어야 한다. CUT을 만들려고 사소한 표현을 격상하지 마라(이슈 발명 금지). 진짜로 깨끗하면 그 항목은 반려하지 않는다.

## E5 교정 원칙 — 정직 ≠ 자기비하
약점을 숨기라는 게 아니다. "검증 계획"으로 프레이밍하라.
예: "수익모델은 솔직히 고민" → "수익모델은 3트랙을 단계 검증, 1순위 X, 1단계 KPI는 [측정예정]".
fix는 항상 이렇게 **그대로 붙여넣을 수 있는 문구**로 준다.

## 정직성 가드
- 없는 사실을 만들지 마라. 제출물에 근거가 없으면 추측하지 말고 "근거 부족"이라 하라.
- 개선용 점수(보수 채점)와 당락 추정은 다른 것이다. 내부 채점은 **개선 엔진**이지 당락 예측기가 아니다.
  honestNote에는 절대 "붙는다/떨어진다"를 단정하지 말고, 경쟁 컷 상대등급과 탈락요인으로만 말하라.

## 출력
반드시 아래 TypeScript 인터페이스 ReviewResult 형태의 **순수 JSON**만 출력한다. 마크다운·설명 문장 금지.
모든 텍스트는 한국어로. topFixes는 점수를 가장 크게 올릴 순서로 정렬.`;
}

/** 사용자 입력을 심사 요청 메시지로 조립 */
export function buildUserPrompt(submission: string, criteria: string): string {
  const crit = criteria.trim()
    ? criteria.trim()
    : '(평가기준 미제공 — 이 제출물이 어떤 자리에 가는지 추정해 일반적 심사 기준으로 평가하되, 추정임을 honestNote에 명시)';
  return `## 이 제출물이 가는 곳 / 평가기준
${crit}

## 심사 대상 제출물
${submission.trim()}

위 제출물을 반려-우선 관점으로 심사하고 ReviewResult JSON만 출력하라.`;
}
